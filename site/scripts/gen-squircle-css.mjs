// Writes src/lib/styles/squircle.css: clip paths for continuous-curvature corners (superellipse, n = 4,
// the same curve as CSS `corner-shape: squircle`). Browsers with corner-shape use it natively; the rest
// fall back to these polygons. Polygons use calc() so they fit any element size without JavaScript.
// Run: node scripts/gen-squircle-css.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const RADII = [12, 16, 22, 28];
const N = 4;
const STEPS = 10;

const fmt = (v) => (Math.round(v * 100) / 100).toString();
const x = (v, fromRight) => (fromRight ? `calc(100% - ${fmt(v)}px)` : `${fmt(v)}px`);

// points of the top left corner from (inset, inset + r) to (inset + r, inset)
function cornerPoints(r, inset) {
	const pts = [];
	for (let i = 0; i <= STEPS; i++) {
		const t = (i / STEPS) * (Math.PI / 2);
		const c = Math.pow(Math.cos(t), 2 / N);
		const s = Math.pow(Math.sin(t), 2 / N);
		pts.push([inset + r - r * c, inset + r - r * s]);
	}
	return pts;
}

// clockwise outline starting at the top edge, end of the top left corner
function outline(r, inset) {
	const p = cornerPoints(r, inset);
	const out = [];
	for (let i = p.length - 1; i >= 0; i--) out.push([p[i][0], p[i][1], true, false]); // top right
	for (let i = 0; i < p.length; i++) out.push([p[i][0], p[i][1], true, true]); // bottom right
	for (let i = p.length - 1; i >= 0; i--) out.push([p[i][0], p[i][1], false, true]); // bottom left
	for (let i = 0; i < p.length; i++) out.push([p[i][0], p[i][1], false, false]); // top left
	return out.map(([a, b, right, bottom]) => `${x(a, right)} ${x(b, bottom)}`);
}

function fill(r) {
	return `polygon(${outline(r, 0).join(', ')})`;
}

// a ring of the given width: outer and inner outlines joined by a seam that cancels out with evenodd
function ring(r, width) {
	const outer = outline(r, 0);
	const inner = outline(Math.max(r - width, 1), width);
	return `polygon(evenodd, ${[...outer, outer[0], ...inner, inner[0]].join(', ')})`;
}

let css = `/* Generated by scripts/gen-squircle-css.mjs. Continuous-curvature corners for browsers without corner-shape. */\n:root {\n`;
for (const r of RADII) {
	css += `\t--sq-fill-${r}: ${fill(r)};\n`;
	css += `\t--sq-ring-${r}: ${ring(r, 1)};\n`;
	css += `\t--sq-focus-${r}: ${ring(r, 2)};\n`;
}
css += `}\n`;
for (const r of RADII) {
	css += `.r-${r} { --r: ${r}px; --sq-fill: var(--sq-fill-${r}); --sq-ring: var(--sq-ring-${r}); --sq-focus: var(--sq-focus-${r}); }\n`;
}
writeFileSync(fileURLToPath(new URL('../src/lib/styles/squircle.css', import.meta.url)), css);
console.log(`wrote squircle.css (${css.length} bytes)`);
